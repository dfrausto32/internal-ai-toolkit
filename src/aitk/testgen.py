"""Spec-derived test writer — a separate agent that never sees the implementation.

Independence is the point: if the model that writes the code also writes the tests, the tests
tend to encode that model's own misreadings of the spec and pass anyway. This module writes
tests from the spec alone, in a separate call with its own prompt, before any code exists. The
resulting file is frozen for the run — the coder never sees or edits it.

Generated tests are weaker evidence than hand-written ones (they can misread the spec too), so
they are labelled as generated and should be reviewed by a human before being trusted.
"""
import ast
from pathlib import Path

from aitk.agents import _strip_fences
from aitk.config import TEST_EFFORT, TEST_MODEL
from aitk.llm import call_claude

_SYSTEM = (
    "You are a senior test engineer. You write pytest suites from a specification alone. "
    "You have NOT seen the implementation and must not guess at its internals: test only the "
    "behavior the spec states, through the public interface the spec defines. "
    "Return ONLY raw Python code — no markdown fences, no commentary."
)

_TEMPLATE = """\
Write a pytest suite for the module described by this spec.

## Spec
{spec}

Requirements:
- The module under test is importable as `{module}`; import it at the top of the file.
- Cover every public function/class and every behavior, validation rule, error case and edge case the spec states.
- Test only what the spec specifies. If the spec is silent on something, do not assert it.
- Assert exact exception types and messages only where the spec fixes them.
- Do not mock the module under test. Keep tests deterministic: no network, no real clock or randomness; use `tmp_path` for files.
- Every test has a one-line docstring naming the spec rule it checks.
- Start the file with this comment: `# Generated by aitk from the spec only (independent of the implementation). Review before treating as ground truth.`
"""

_FIX_TEMPLATE = """\
Your previous test file had these problems:
{problems}

Return the corrected, complete test file (code only).

PREVIOUS FILE:
{draft}
"""


def has_tests(test_dir: str) -> bool:
    """True if the directory already contains pytest test files."""
    root = Path(test_dir)
    if not root.is_dir():
        return False
    return any(root.rglob("test_*.py")) or any(root.rglob("*_test.py"))


def validate_tests(code: str, module: str) -> list[str]:
    """Return validation problems with a generated test file (empty list = usable)."""
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        return [f"not valid Python (line {exc.lineno}: {exc.msg})"]
    problems = []
    if not any(
        isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name.startswith("test_")
        for n in ast.walk(tree)
    ):
        problems.append("contains no test_ functions")
    imported = {
        alias.name.split(".")[0]
        for n in ast.walk(tree) if isinstance(n, ast.Import) for alias in n.names
    } | {
        (n.module or "").split(".")[0]
        for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)
    }
    if module not in imported:
        problems.append(f"never imports the module under test (`{module}`)")
    return problems


def generate_tests(spec_text: str, module: str, max_attempts: int = 2) -> tuple[str, list[str], dict]:
    """Write a test file from the spec. Returns (code, remaining_problems, summed_usage)."""
    total = {"input_tokens": 0, "output_tokens": 0, "cache_read_tokens": 0, "cache_write_tokens": 0}
    prompt = _TEMPLATE.format(spec=spec_text, module=module)
    code, problems = "", ["no tests produced"]

    for _ in range(max_attempts):
        text, usage = call_claude(
            TEST_MODEL, prompt, system=_SYSTEM, max_tokens=16000, effort=TEST_EFFORT, cache=False
        )
        for key in total:
            total[key] += usage[key]
        if usage["stop_reason"] == "max_tokens":
            raise RuntimeError("test generation hit the output cap — split the spec")
        code = _strip_fences(text)
        problems = validate_tests(code, module)
        if not problems:
            break
        prompt = _FIX_TEMPLATE.format(problems="\n".join(f"- {p}" for p in problems), draft=code)

    return code, problems, total


def write_generated_tests(test_dir: str, module: str, code: str) -> Path:
    """Write the generated suite into the test directory and return its path."""
    path = Path(test_dir) / f"test_{module}_generated.py"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(code if code.endswith("\n") else code + "\n")
    return path
