"""Hand-written acceptance tests for aitk.plan — the Phase 5 node-spec schema.

Ground truth: these tests are authored by hand, never generated by the code under test.
"""
import pytest

from aitk.plan import (
    Criterion,
    NodeSpec,
    find_scope_conflicts,
    parse_node_spec,
    paths_conflict,
    scopes_overlap,
    topological_levels,
    validate_plan,
)


# --- parsing ---

def test_parse_node_spec_reads_all_fields(tmp_path):
    spec = tmp_path / "api.md"
    spec.write_text(
        "---\n"
        "id: api-layer\n"
        "language: python\n"
        "frameworks: [fastapi]\n"
        "depends_on: [models]\n"
        "output_scope: [src/api/, src/api.py]\n"
        "validation_kind: automated\n"
        "test_command: pytest tests/api -q\n"
        "estimated_lines: 180\n"
        "acceptance_criteria:\n"
        "  - id: AC-1\n"
        "    text: GET /items returns 200\n"
        "  - POST /items returns 201\n"
        "---\n"
        "# Node: API layer\n"
        "Expanded prose.\n"
    )

    node = parse_node_spec(str(spec))

    assert node.id == "api-layer"
    assert node.frameworks == ["fastapi"]
    assert node.depends_on == ["models"]
    assert node.output_scope == ["src/api/", "src/api.py"]
    assert node.validation_kind == "automated"
    assert node.test_command == "pytest tests/api -q"
    assert node.estimated_lines == 180
    assert node.body == "# Node: API layer\nExpanded prose."


def test_acceptance_criteria_normalize_string_and_dict_forms():
    node = NodeSpec.from_meta({
        "id": "n",
        "acceptance_criteria": [
            "plain string criterion",
            {"id": "AC-custom", "text": "explicit id"},
        ],
    })
    assert node.acceptance_criteria == [
        Criterion(id="AC-1", text="plain string criterion"),
        Criterion(id="AC-custom", text="explicit id"),
    ]


def test_missing_id_is_rejected():
    with pytest.raises(ValueError, match="missing required field 'id'"):
        NodeSpec.from_meta({"language": "python"})


# --- plan validation ---

def _node(nid, deps=None, **kw):
    return NodeSpec(id=nid, depends_on=list(deps or []), **kw)


def test_valid_plan_has_no_errors():
    nodes = [_node("models"), _node("api", deps=["models"])]
    assert validate_plan(nodes) == []


def test_duplicate_node_id_flagged():
    errors = validate_plan([_node("dup"), _node("dup")])
    assert any("duplicate node id" in e for e in errors)


def test_depends_on_unknown_node_flagged():
    errors = validate_plan([_node("api", deps=["ghost"])])
    assert any("unknown node 'ghost'" in e for e in errors)


def test_self_dependency_flagged():
    errors = validate_plan([_node("loop", deps=["loop"])])
    assert any("depends on itself" in e for e in errors)


def test_dependency_cycle_flagged():
    nodes = [_node("a", deps=["b"]), _node("b", deps=["a"])]
    errors = validate_plan(nodes)
    assert any("dependency cycle" in e for e in errors)


def test_bad_validation_kind_flagged():
    errors = validate_plan([_node("n", validation_kind="maybe")])
    assert any("invalid validation_kind" in e for e in errors)


def test_duplicate_criterion_id_flagged():
    node = NodeSpec(
        id="n",
        acceptance_criteria=[Criterion("AC-1", "a"), Criterion("AC-1", "b")],
    )
    errors = validate_plan([node])
    assert any("duplicate acceptance-criterion id" in e for e in errors)


# --- topological levels ---

def test_topological_levels_groups_independent_nodes():
    nodes = [
        _node("models"),
        _node("util"),
        _node("api", deps=["models"]),
        _node("cli", deps=["api", "util"]),
    ]
    levels = topological_levels(nodes)
    assert levels == [["models", "util"], ["api"], ["cli"]]


def test_topological_levels_raises_on_cycle():
    nodes = [_node("a", deps=["b"]), _node("b", deps=["a"])]
    with pytest.raises(ValueError, match="cycle"):
        topological_levels(nodes)


# --- write-scope overlap ---

def test_paths_conflict_exact_and_prefix():
    assert paths_conflict("src/api.py", "src/api.py")        # exact
    assert paths_conflict("src/api/", "src/api/routes.py")   # file under dir
    assert paths_conflict("src/api/routes.py", "src/api")    # dir prefix of file
    assert not paths_conflict("src/api.py", "src/models.py")  # siblings
    assert not paths_conflict("src/api", "src/apiv2")         # prefix string but not path-prefix


def test_scopes_overlap_any_pair():
    assert scopes_overlap(["src/a.py", "src/b.py"], ["src/b.py"])
    assert not scopes_overlap(["src/a.py"], ["src/b.py", "tests/"])


def test_find_scope_conflicts_returns_sorted_pairs():
    nodes = [
        NodeSpec(id="a", output_scope=["src/shared/"]),
        NodeSpec(id="b", output_scope=["src/shared/util.py"]),
        NodeSpec(id="c", output_scope=["src/other.py"]),
    ]
    assert find_scope_conflicts(nodes) == [("a", "b")]
